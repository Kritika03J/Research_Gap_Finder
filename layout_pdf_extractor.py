def _sort_single_flow(lines):
    """Top-to-bottom, left-to-right inside one flow (rows grouped by vertical overlap)."""
    key = lambda l: (l.y0 if l.kind == "placeholder" else l.cy, l.x0)
    rows = []
    for l in sorted(lines, key=key):
        if rows:
            ref = rows[-1][0]
            ov = min(ref.y1, l.y1) - max(ref.y0, l.y0)
            if (ref.kind == "text" and l.kind == "text"
                    and ov > 0.5 * min(ref.height, l.height)
                    and max(ref.height, l.height) <= 2.5 * min(ref.height, l.height)):
                rows[-1].append(l)
                continue
        rows.append([l])
    out = []
    for r in rows:
        out.extend(sorted(r, key=lambda l: l.x0))
    return out


def sort_reading_blocks(lines, page_w, page_h, gutter=None):
    """
    Single column: top->bottom, left->right.
    Two columns: column 1 completely, then column 2.
    """
    if not lines:
        return []
    if gutter is None:
        gutter = detect_gutter(lines, page_w)
    if gutter is None:
        return _sort_single_flow(lines)

    def is_full(l):
        return (l.width > FULL_WIDTH_RATIO * page_w
                or (l.x0 < gutter - 15 and l.x1 > gutter + 15))

    ordered, left, right = [], [], []
    for l in sorted(lines, key=lambda l: (l.y0, l.x0)):
        if is_full(l):
            ordered += _sort_single_flow(left) + _sort_single_flow(right)
            left, right = [], []
            ordered.append(l)
        elif l.cx < gutter:
            left.append(l)
        else:
            right.append(l)
    ordered += _sort_single_flow(left) + _sort_single_flow(right)
    return ordered


def _lines_to_text(ordered):
    """Join ordered lines into paragraphs (dehyphenate, break on gaps / column jumps)."""
    widths = sorted(l.width for l in ordered if l.kind == "text")
    ref_w = widths[int(0.9 * (len(widths) - 1))] if widths else 0.0
    paras, cur, prev = [], "", None
    for l in ordered:
        if l.kind == "placeholder":
            if cur:
                paras.append(cur)
            paras.append(l.text)
            cur, prev = "", None
            continue
        brk = prev is None
        if prev is not None:
            gap = l.y0 - prev.y1
            if (gap > 0.6 * prev.height or l.y0 < prev.y0 - 2
                    or (prev.text.endswith((".", ":", "!", "?")) and prev.width < 0.8 * ref_w
                        and gap > -1)
                    or (prev.bold != l.bold and abs(prev.size - l.size) > 0.8)):
                brk = True
        if brk:
            if cur:
                paras.append(cur)
            cur = l.text
        elif cur.endswith("-") and not cur.endswith(" -") and l.text[:1].islower():
            cur = cur[:-1] + l.text
        else:
            cur += " " + l.text
        prev = l
    if cur:
        paras.append(cur)
    return "\n\n".join(p.strip() for p in paras if p.strip())


def mask_and_compile_text(lines, registry, page_w, page_h, gutter=None):
    """Drop lines inside table/figure boxes, inject placeholders at their position."""
    boxes = [r["mask_bbox"] for r in registry]

    def masked(l):
        return any(_inter_area(l.bbox, b) > 0.45 * _area(l.bbox) or _center_inside(l.bbox, b)
                   for b in boxes)

    kept = [l for l in lines if not masked(l)]
    for r in registry:
        b = r["mask_bbox"]
        kept.append(TextLine(b[0], b[1], b[2], b[3], r["placeholder"], kind="placeholder"))
    return _lines_to_text(sort_reading_blocks(kept, page_w, page_h, gutter))


def save_debug_image(page, path, header_bbox, captions, registry, gutter, dpi=100):
    """Annotated page render: header=green, captions=orange, tables=red,
    figures=blue, column gutter=purple."""
    from PIL import ImageDraw
    pix = page.get_pixmap(dpi=dpi, alpha=False)
    img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")
    d, k = ImageDraw.Draw(img), dpi / 72.0

    def box(b, color, w=2):
        d.rectangle([b[0] * k, b[1] * k, b[2] * k, b[3] * k], outline=color, width=w)

    if header_bbox:
        box(header_bbox, (0, 160, 0))
    for c in captions:
        box(c["bbox"], (255, 140, 0), 1)
    for r in registry:
        box(r["mask_bbox"], (220, 0, 0) if r["kind"] == "table" else (0, 80, 255))
    if gutter is not None:
        d.line([gutter * k, 0, gutter * k, img.size[1]], fill=(150, 0, 200), width=1)
    img.save(path)



def detect_scanned_page(page, min_chars=MIN_CHARS_PER_PAGE):
    """True if the page has (almost) no extractable text, i.e. needs OCR."""
    try:
        chars = len(re.sub(r"\s+", "", page.get_text("text")))
    except Exception as exc:
        log.warning("text extraction failed on page %s: %s", page.number + 1, exc)
        return True
    if chars < min_chars:
        return True
    if chars < 4 * min_chars:  # tiny text layer + page-sized image => scanned
        try:
            page_area = page.rect.get_area()
            for info in page.get_image_info():
                if fitz.Rect(info["bbox"]).get_area() >= 0.85 * page_area:
                    return True
        except Exception:
            pass
    return False


def _is_margin_stamp(x0, y0, x1, y1, text, page_w, page_h):
    """
    Strips top headers, bottom IEEE copyright / download banners,
    and rotated side margin stamps on all pages.
    """
    # 1. Extreme left/right edge or rotated vertical margin text
    if x1 < 0.065 * page_w or x0 > 0.935 * page_w:
        return True
    if (y1 - y0) > 1.4 * (x1 - x0) and len(text) >= 3:
        return True

    # 2. Top running header (e.g. Conference name, ISBN, CFP lines)
    if y1 < 0.055 * page_h:
        return True

    # 3. Bottom footer / license banner / page numbers
    if y0 > 0.93 * page_h:
        return True

    # 4. Specific IEEE / conference patterns appearing near edges
    lowered = text.lower()
    if (y0 < 0.08 * page_h or y1 > 0.91 * page_h) and (
        "ieee" in lowered or "isbn" in lowered or "cfp" in lowered or
        "conference" in lowered or "authorized licensed use" in lowered or
        "downloaded on" in lowered
    ):
        return True

    return False


def _digital_lines_and_words(page):
    lines = []
    page_w = page.rect.width
    page_h = page.rect.height
    for block in page.get_text("dict").get("blocks", []):
        if block.get("type") != 0:
            continue
        for ln in block.get("lines", []):
            dx, dy = ln.get("dir", (1.0, 0.0))
            if abs(dy) > 0.3:          # vertical text
                continue
            spans = [s for s in ln.get("spans", []) if s.get("text", "").strip()]
            if not spans:
                continue
            text = "".join(s["text"] for s in ln["spans"]).strip()
            x0, y0, x1, y1 = ln["bbox"]
            if _is_margin_stamp(x0, y0, x1, y1, text, page_w, page_h):
                continue
            lines.append(TextLine(
                x0, y0, x1, y1, text,
                size=max(s["size"] for s in spans),
                bold=any(s["flags"] & 16 for s in spans)))

    words = [
        tuple(w[:5]) for w in page.get_text("words")
        if not _is_margin_stamp(w[0], w[1], w[2], w[3], w[4], page_w, page_h)
    ]
    return lines, words


def _ocr_lines_and_words(page, dpi=OCR_DPI):
    """Run tesseract; returns (lines, words, PIL image). Raises on OCR failure."""
    if pytesseract is None:
        raise RuntimeError("pytesseract is not installed")
    pix = page.get_pixmap(dpi=dpi, alpha=False)
    img = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGB")
    data = pytesseract.image_to_data(
        img, output_type=pytesseract.Output.DICT, config="--psm 3")
    scale = 72.0 / dpi
    page_w = page.rect.width
    page_h = page.rect.height

    groups, words = {}, []
    for i, raw in enumerate(data["text"]):
        txt = (raw or "").strip()
        try:
            conf = float(data["conf"][i])
        except (TypeError, ValueError):
            conf = -1.0
        if not txt or conf < MIN_OCR_CONF:
            continue
        x0 = data["left"][i] * scale
        y0 = data["top"][i] * scale
        x1 = x0 + data["width"][i] * scale
        y1 = y0 + data["height"][i] * scale
        if _is_margin_stamp(x0, y0, x1, y1, txt, page_w, page_h):
            continue
        words.append((x0, y0, x1, y1, txt))
        key = (data["block_num"][i], data["par_num"][i], data["line_num"][i])
        groups.setdefault(key, []).append((x0, y0, x1, y1, txt))
    lines = []
    for ws in groups.values():
        ws.sort(key=lambda w: w[0])
        box = _union([w[:4] for w in ws])
        lines.append(TextLine(*box, text=" ".join(w[4] for w in ws),
                              size=max(w[3] - w[1] for w in ws) * 0.9))
    return lines, words, img


def merge_row_fragments(lines):
    """
    Glue small fragments (superscripts, inline math, split spans) that sit on one row.
    Two *substantial* lines are never merged: they are neighbouring columns/blocks
    whose boxes merely touch (trailing spaces of justified text), and merging them
    creates phantom full-width lines that wreck zoning and reading order.
    """
    out = []
    for ln in sorted(lines, key=lambda l: (round(l.cy), l.x0)):
        merged = False
        for tgt in reversed(out[-6:]):
            ov = min(tgt.y1, ln.y1) - max(tgt.y0, ln.y0)
            gap = ln.x0 - tgt.x1
            both_long = len(tgt.text) >= 12 and len(ln.text) >= 12
            similar_h = max(tgt.height, ln.height) <= 2.5 * min(tgt.height, ln.height)
            if (ov > 0.5 * min(tgt.height, ln.height) and -1.0 <= gap <= 0.7 * tgt.size
                    and similar_h and not both_long):
                tgt.text += (" " if gap > 0.15 * tgt.size else "") + ln.text
                tgt.x1 = max(tgt.x1, ln.x1)
                tgt.y0, tgt.y1 = min(tgt.y0, ln.y0), max(tgt.y1, ln.y1)
                tgt.size = max(tgt.size, ln.size)
                tgt.bold = tgt.bold and ln.bold
                merged = True
                break
        if not merged:
            out.append(ln)
    return out


_ANY_CAPTION_RE = re.compile(
    r"\b(?:Table|TABLE|Tab\.|Figure|FIGURE|Fig\.?|FIG\.?)\s*(?:\d+|[IVXLC]+)\s*[.:]")


def split_side_by_side_captions(lines, words):
    """
    Two captions that share one row (e.g. 'TABLE III ...' in the left column and
    'TABLE IV ...' in the right column) can end up as ONE text line. That line looks
    full-width, so both tables get treated as a single table. This cuts such a line
    at the wide horizontal gap between the captions, using word positions.
    Only lines holding >= 2 caption labels are touched; every other line is returned
    unchanged, so nothing else on the page is affected.
    """
    out = []
    for ln in lines:
        if ln.kind != "text" or len(_ANY_CAPTION_RE.findall(ln.text)) < 2:
            out.append(ln)
            continue
        ws = [w for w in words
              if w[0] >= ln.x0 - 1.5 and w[2] <= ln.x1 + 1.5
              and min(w[3], ln.y1) - max(w[1], ln.y0) > 0.5 * min(w[3] - w[1], ln.height)]
        ws.sort(key=lambda w: w[0])
        min_gap = max(3.0 * ln.size, 20.0)
        groups = [[ws[0]]] if ws else []
        for w in ws[1:]:
            if w[0] - groups[-1][-1][2] > min_gap:
                groups.append([w])
            else:
                groups[-1].append(w)
        texts = [" ".join(w[4] for w in g) for g in groups]
        # split only if the wide gap really separates caption labels
        if len(groups) < 2 or sum(1 for t in texts if _ANY_CAPTION_RE.search(t)) < 2:
            out.append(ln)
            continue
        for g, t in zip(groups, texts):
            b = _union([w[:4] for w in g])
            out.append(TextLine(b[0], b[1], b[2], b[3], t, size=ln.size, bold=ln.bold))
    return out


def drop_page_furniture(lines, page_h):
    """Remove any leftover header/footer artifacts or standalone page numbers."""
    keep = []
    for ln in lines:
        in_margin = ln.y1 < 0.055 * page_h or ln.y0 > 0.93 * page_h
        t = ln.text.strip()
        if in_margin:
            continue
        if ln.y0 > 0.90 * page_h and (
            re.fullmatch(r"[\-\u2013 ]*\d{1,4}[\-\u2013 ]*", t) or
            "authorized licensed use" in t.lower() or
            "ieee" in t.lower()
        ):
            continue
        keep.append(ln)
    return keep



def clean_table(rows):
    """Normalise cells, drop empty rows/cols, validate (anti-ghost filter)."""
    if not rows:
        return None
    width = max(len(r) for r in rows)
    norm = [[re.sub(r"\s+", " ", "" if c is None else str(c)).strip() for c in r]
            + [""] * (width - len(r)) for r in rows]
    df = pd.DataFrame(norm)
    df = df.loc[~(df == "").all(axis=1)]
    df = df.loc[:, ~(df == "").all(axis=0)]
    if df.empty:
        return None
    df.columns = range(df.shape[1])
    df = df.reset_index(drop=True)
    return df if validate_table(df) else None


def validate_table(df):
    rows, cols = df.shape
    if rows < MIN_TABLE_ROWS or cols < MIN_TABLE_COLS:
        return False
    cells = [str(v).strip() for v in df.values.ravel()]
    # Only count genuinely empty cells as weak (single-digit numbers like '0' or '6' are valid!)
    empty_cnt = sum(1 for c in cells if c == "")
    if empty_cnt / float(len(cells)) > MAX_EMPTY_CELL_RATIO:
        return False
    non_empty = [c for c in cells if c]
    if not non_empty:
        return False
    if sum(len(c) for c in non_empty) / float(len(non_empty)) > 65:  # paragraphs, not a table
        return False
    return True


def _format_df_as_text_table(df):
    """Render a DataFrame as a clean pipe-aligned text table so columns stay aligned."""
    rows = [[str(v) for v in r] for r in df.values.tolist()]
    if not rows:
        return ""
    ncols = len(rows[0])
    col_w = [max(len(r[c]) for r in rows) for c in range(ncols)]
    lines = []
    for idx, r in enumerate(rows):
        line = " | ".join(r[c].ljust(col_w[c]) for c in range(ncols)).rstrip()
        lines.append(line)
        if idx == 0 and len(rows) > 1:
            sep = "-+-".join("-" * max(col_w[c], 3) for c in range(ncols))
            lines.append(sep)
    return "\n".join(lines)


def _get_horizontal_rules(page):
    """
    Extract horizontal vector lines / thin rectangles that act as table rules.
    Returns merged list of (x0, y, x1).
    """
    pw, ph = page.rect.width, page.rect.height
    raw = []
    try:
        for d in page.get_drawings():
            r = d["rect"]
            w, h = r.x1 - r.x0, r.y1 - r.y0
            if r.y1 < 0.06 * ph or r.y0 > 0.92 * ph:
                continue
            if h <= 3.5 and w >= 20.0:
                raw.append((r.x0, (r.y0 + r.y1) / 2.0, r.x1))
    except Exception as exc:
        log.debug("rule extraction failed: %s", exc)
        return []
    raw.sort(key=lambda r: (round(r[1], 1), r[0]))
    merged = []
    for x0, y, x1 in raw:
        if merged and abs(y - merged[-1][1]) <= 2.0 and x0 <= merged[-1][2] + 6.0:
            prev = merged[-1]
            merged[-1] = (min(prev[0], x0), (prev[1] + y) / 2.0, max(prev[2], x1))
        else:
            merged.append((x0, y, x1))
    return merged


def _has_vertical_grid_lines(page, bbox):
    """True if bbox contains vertical border lines (i.e. a true lattice grid table)."""
    v_count = 0
    try:
        for d in page.get_drawings():
            r = d["rect"]
            w, h = r.x1 - r.x0, r.y1 - r.y0
            if w <= 3.0 and h >= 18.0 and _overlaps((r.x0, r.y0, r.x1, r.y1), bbox):
                v_count += 1
    except Exception:
        pass
    return v_count >= 2


def _spanning_header_phrases(rows):
    """
    A header phrase (e.g. 'Training (%)') that sits above two separate sub-columns
    (e.g. 'KNN' and 'SVM') and overlaps both of them. Such a phrase fills the empty
    gap between those sub-columns and would glue them into ONE column, so it must not
    be used when the column boundaries are computed.
    A phrase is flagged only if, in the OTHER rows, it overlaps two phrases that are
    clearly separated from each other horizontally.
    """
    flagged = set()
    if len(rows) < 3:
        return flagged
    for ri, r in enumerate(rows):
        for p in r["phrases"]:
            hit = []
            for rj, o in enumerate(rows):
                if rj == ri:
                    continue
                for q in o["phrases"]:
                    if min(p[2], q[2]) - max(p[0], q[0]) > 1.0:
                        hit.append(q)
            hit.sort(key=lambda q: q[0])
            for a in hit:
                if any(b[0] - a[2] > 4.0 and b[0] > p[0] - 1.0 and a[2] < p[2] + 1.0
                       for b in hit):
                    flagged.add(id(p))
                    break
    return flagged


def table_from_words(words, bbox, h_rules=None):
    """
    Phrase-interval column clustering for booktabs and borderless academic tables.
    1. Groups words on the same y-baseline into rows.
    2. Within each row, merges adjacent words separated by normal space into cell phrases.
    3. Detects column boundaries from the horizontal alignment of cell phrases across rows
       (ignoring wide spanning headers when finding sub-columns).
    4. Optionally merges multi-line header rows that sit above the header horizontal rule
       when no sub-header rule splits them.
    """
    sel = [w for w in words if _center_inside(w[:4], bbox) and w[4].strip()]
    if len(sel) < 4:
        return None, None
    med_h = _median([w[3] - w[1] for w in sel], 9.0)
    sel.sort(key=lambda w: ((w[1] + w[3]) / 2.0, w[0]))

    # 1. Group words into horizontal visual rows
    rows = []
    for w in sel:
        cy = (w[1] + w[3]) / 2.0
        if rows and abs(cy - rows[-1]["cy"]) < 0.55 * med_h:
            rows[-1]["w"].append(w)
            n = len(rows[-1]["w"])
            rows[-1]["cy"] = (rows[-1]["cy"] * (n - 1) + cy) / n
            rows[-1]["y0"] = min(rows[-1]["y0"], w[1])
            rows[-1]["y1"] = max(rows[-1]["y1"], w[3])
        else:
            rows.append({"cy": cy, "y0": w[1], "y1": w[3], "w": [w]})
    if len(rows) < MIN_TABLE_ROWS:
        return None, None

    # 2. Within each row, merge words that belong to the same cell phrase
    phrase_gap = max(5.5, 0.72 * med_h)
    for r in rows:
        ws = sorted(r["w"], key=lambda w: w[0])
        phrases = []
        for w in ws:
            if phrases and (w[0] - phrases[-1][2]) <= phrase_gap:
                p = phrases[-1]
                phrases[-1] = (p[0], min(p[1], w[1]), max(p[2], w[2]), max(p[3], w[3]),
                               p[4] + " " + w[4])
            else:
                phrases.append((w[0], w[1], w[2], w[3], w[4]))
        r["phrases"] = phrases

    # 3. Determine column intervals via 1D coverage of phrase boxes
    all_phrases = [p for r in rows for p in r["phrases"]]
    if not all_phrases:
        return None, None
    x_min = int(math.floor(min(p[0] for p in all_phrases))) - 2
    x_max = int(math.ceil(max(p[2] for p in all_phrases))) + 2
    table_w = max(x_max - x_min, 1)

    max_phrases_in_row = max(len(r["phrases"]) for r in rows)
    bridge_ids = _spanning_header_phrases(rows)
    non_spanning = [
        p for p in all_phrases
        if not (max_phrases_in_row >= 3 and (p[2] - p[0]) > 0.38 * table_w)
        and id(p) not in bridge_ids
    ] or all_phrases

    cover = [0] * (x_max - x_min + 1)
    pad = 1
    for r in rows:
        hit = set()
        for p in r["phrases"]:
            if p not in non_spanning:
                continue
            a = max(0, int(math.floor(p[0])) - pad - x_min)
            b = min(len(cover) - 1, int(math.ceil(p[2])) + pad - x_min)
            for x in range(a, b + 1):
                hit.add(x)
        for x in hit:
            cover[x] += 1

    cols, start = [], None
    for i, c in enumerate(cover):
        if c > 0 and start is None:
            start = i
        elif c == 0 and start is not None:
            cols.append([start + x_min, i - 1 + x_min])
            start = None
    if start is not None:
        cols.append([start + x_min, len(cover) - 1 + x_min])

    if len(cols) < MIN_TABLE_COLS and max_phrases_in_row >= MIN_TABLE_COLS:
        anchor_row = max(rows, key=lambda r: len(r["phrases"]))
        cols = [[p[0], p[2]] for p in anchor_row["phrases"]]

    if len(cols) < MIN_TABLE_COLS:
        return None, None

    # Assign every phrase in every row to the best-matching column
    grid = []
    for r in rows:
        cells = [[] for _ in cols]
        for p in r["phrases"]:
            px0, _, px1, _, ptxt = p
            pcx = (px0 + px1) / 2.0
            best_k, best_ov = None, 0.0
            for k, (cx0, cx1) in enumerate(cols):
                ov = max(0.0, min(px1, cx1) - max(px0, cx0))
                if id(p) in bridge_ids and ov > 0:
                    best_k = k             # bridging header -> leftmost column it covers
                    break
                if ov > best_ov:
                    best_ov, best_k = ov, k
            if best_k is None:
                best_k = min(
                    range(len(cols)),
                    key=lambda k: 0.0 if cols[k][0] <= pcx <= cols[k][1]
                    else min(abs(pcx - cols[k][0]), abs(pcx - cols[k][1]))
                )
            cells[best_k].append(ptxt)
        grid.append([" ".join(c).strip() for c in cells])

    # 4. Merge wrapped multi-line header rows when they lie above the main header separator rule
    if h_rules and len(grid) >= 3:
        ub = _union([w[:4] for w in sel])
        inner_rules = [
            rl for rl in h_rules
            if ub[1] + 2.0 < rl[1] < ub[3] - 2.0
            and _x_overlap_ratio((rl[0], rl[1] - 1, rl[2], rl[1] + 1), ub[0], ub[2]) > 0.20
        ]
        r0_y1, r1_y0, r1_y1, r2_y0 = rows[0]["y1"], rows[1]["y0"], rows[1]["y1"], rows[2]["y0"]
        rule_between_0_1 = any(r0_y1 - 1.5 <= rl[1] <= r1_y0 + 1.5 for rl in inner_rules)
        rule_between_1_2 = any(r1_y1 - 1.5 <= rl[1] <= r2_y0 + 1.5 for rl in inner_rules)
        if not rule_between_0_1 and rule_between_1_2:
            merged_hdr = [
                (" ".join(x for x in (grid[0][c], grid[1][c]) if x)).strip()
                for c in range(len(cols))
            ]
            grid = [merged_hdr] + grid[2:]
        elif rule_between_0_1 and len(rows) >= 3:
            r2_rule = len(rows) >= 3 and any(r1_y1 - 1.5 <= rl[1] <= r2_y0 + 1.5 for rl in inner_rules)
            if r2_rule and grid[1][0].startswith("(") and grid[0][0]:
                grid[0][0] = (grid[0][0] + " " + grid[1][0]).strip()
                grid[1][0] = ""

    return grid, _union([w[:4] for w in sel])


def _plumber_tables(plpage, bbox, settings, shift):
    """Run one pdfplumber strategy inside bbox; returns [(rows, bbox_fitz_coords)]."""
    pb = plpage.bbox
    b = (bbox[0] + shift[0], bbox[1] + shift[1], bbox[2] + shift[0], bbox[3] + shift[1])
    b = (max(b[0], pb[0]), max(b[1], pb[1]), min(b[2], pb[2]), min(b[3], pb[3]))
    if b[2] - b[0] < 5 or b[3] - b[1] < 5:
        return []
    crop = plpage.crop(b)
    found = []
    for tbl in crop.find_tables(table_settings=settings):
        try:
            rows = tbl.extract(x_tolerance=2, y_tolerance=2)
        except TypeError:
            rows = tbl.extract()
        tb = tbl.bbox
        found.append((rows, (tb[0] - shift[0], tb[1] - shift[1],
                             tb[2] - shift[0], tb[3] - shift[1])))
    return found


def _extract_table_in_bbox(page, plpage, shift, words, bbox, use_plumber, wide=None, h_rules=None):
    """
    1. If the table has real vertical & horizontal grid lines, try pdfplumber lattice.
    2. Otherwise (booktabs / horizontal-only rules / borderless tables), use the
       phrase-interval word reconstructor (`table_from_words`).
    """
    check_box = wide if wide else bbox
    if use_plumber and _has_vertical_grid_lines(page, check_box):
        try:
            found = _plumber_tables(plpage, check_box, PLUMBER_LATTICE, shift)
            found.sort(key=lambda f: _area(f[1]), reverse=True)
            for rows, tb in found:
                df = clean_table(rows)
                if df is not None:
                    log.debug("table accepted via lattice strategy")
                    return df, tb
        except Exception as exc:
            log.debug("pdfplumber lattice failed: %s", exc)

    rows, tb = table_from_words(words, bbox, h_rules=h_rules)
    if rows:
        df = clean_table(rows)
        if df is not None:
            log.debug("table accepted via phrase-alignment extractor")
            return df, tb
    return None, None


def _is_prose_row(row_text, row_width, col_width, has_multi_spans):
    """
    Detects body-paragraph lines.
    CRITICAL: A row with multiple separate cell spans (`has_multi_spans=True`)
    is a multi-column table row, NEVER a single prose paragraph line!
    """
    t = row_text.strip()
    if re.match(r"^(?:Table|TABLE|Fig\.?|Figure)\s+\d+\s+(?:shows|illustrates|presents|depicts|compares|summarizes)\b", t):
        return True
    if has_multi_spans:
        return False
    if _paragraph_like(TextLine(0, 0, row_width, 10, t)):
        return True
    if row_width >= 0.76 * col_width and len(t) >= 35:
        alpha_ratio = sum(c.isalpha() for c in t) / float(max(len(t), 1))
        word_cnt = len(t.split())
        if alpha_ratio >= 0.65 and word_cnt >= 6:
            return True
    return False


def _table_region_from_rules(cap, page_w, gutter, h_rules):
    """
    Determine the horizontal (x0, x1) region of a table by inspecting the first
    horizontal border rule right below the caption. If the rule crosses the page
    gutter, the table is full-width even if its caption was shorter.
    """
    cb = cap["bbox"]
    base_reg = _column_region(cb, page_w, gutter)
    if not h_rules:
        return base_reg
    below_rules = [
        (rx0, ry, rx1) for rx0, ry, rx1 in h_rules
        if cb[3] - 2.0 <= ry <= cb[3] + 28.0
        and min(cb[2], rx1) - max(cb[0], rx0) > 15.0
    ]
    if not below_rules:
        return base_reg
    below_rules.sort(key=lambda r: r[1])
    rx0, _, rx1 = below_rules[0]
    if gutter is not None and rx0 < gutter - 15.0 and rx1 > gutter + 15.0:
        return (0.0, page_w)
    return (min(base_reg[0], max(0.0, rx0 - 4.0)),
            max(base_reg[1], min(page_w, rx1 + 4.0)))


def _scan_table_lines(cap, lines, region, direction, other_caps, skip_ids, h_rules=None):
    """
    Collect the tabular lines adjacent to a caption (below it, or above it).
    Groups lines into visual horizontal rows first and stops cleanly at the
    table's bottom horizontal rule or at the start of body prose.
    """
    xr0, xr1 = region
    col_w = max(xr1 - xr0, 50.0)
    cb = cap["bbox"]
    pool = [l for l in lines if id(l) not in skip_ids and xr0 - 2 <= l.cx <= xr1 + 2]
    lh = _median([l.height for l in pool], cap["lines"][0].height)

    if direction == "below":
        pool = [l for l in pool if l.y0 >= cb[3] - 2]
        stops = [c["bbox"][1] for c in other_caps
                 if c is not cap and c["bbox"][1] >= cb[3] + 3
                 and _x_overlap_ratio(c["bbox"], xr0, xr1) > 0.3]
        stop = min(stops) if stops else float("inf")
    else:
        pool = [l for l in pool if l.y1 <= cb[1] + 2]
        stops = [c["bbox"][3] for c in other_caps
                 if c is not cap and c["bbox"][3] <= cb[1] - 3
                 and _x_overlap_ratio(c["bbox"], xr0, xr1) > 0.3]
        stop = max(stops) if stops else float("-inf")

    if not pool:
        return []

    # Group pool lines into visual horizontal rows
    pool.sort(key=lambda l: (l.cy, l.x0))
    vrows = []
    for l in pool:
        if vrows and abs(l.cy - vrows[-1]["cy"]) < 0.55 * lh:
            vrows[-1]["lines"].append(l)
            n = len(vrows[-1]["lines"])
            vrows[-1]["cy"] = (vrows[-1]["cy"] * (n - 1) + l.cy) / n
            vrows[-1]["y0"] = min(vrows[-1]["y0"], l.y0)
            vrows[-1]["y1"] = max(vrows[-1]["y1"], l.y1)
            vrows[-1]["x0"] = min(vrows[-1]["x0"], l.x0)
            vrows[-1]["x1"] = max(vrows[-1]["x1"], l.x1)
        else:
            vrows.append({
                "cy": l.cy, "y0": l.y0, "y1": l.y1,
                "x0": l.x0, "x1": l.x1, "lines": [l]
            })

    if direction == "below":
        vrows.sort(key=lambda r: r["y0"])
        edge = cb[3]
    else:
        vrows.sort(key=lambda r: -r["y1"])
        edge = cb[1]

    # Filter horizontal rules that belong to this column/region
    reg_rules = []
    if h_rules:
        for rx0, ry, rx1 in h_rules:
            if _x_overlap_ratio((rx0, ry - 1, rx1, ry + 1), xr0, xr1) >= 0.25:
                reg_rules.append((rx0, ry, rx1))
        reg_rules.sort(key=lambda r: r[1])

    picked_rows = []
    full_rules_crossed = 0
    for r in vrows:
        if direction == "below":
            if r["y0"] >= stop - 1:
                break
            gap = r["y0"] - edge
            new_rules = [rl for rl in reg_rules if edge - 1.5 <= rl[1] <= r["y0"] + 1.5]
        else:
            if r["y1"] <= stop + 1:
                break
            gap = edge - r["y1"]
            new_rules = [rl for rl in reg_rules if r["y1"] - 1.5 <= rl[1] <= edge + 1.5]

        # Count how many full-column-width horizontal rules we just crossed
        full_new = [rl for rl in new_rules if (rl[2] - rl[0]) >= 0.55 * col_w]

        row_lines = sorted(r["lines"], key=lambda l: l.x0)
        row_text = " ".join(l.text for l in row_lines)
        row_w = r["x1"] - r["x0"]
        has_multi_spans = len(row_lines) >= 2

        if picked_rows and full_new:
            full_rules_crossed += len(full_new)
            # Standard booktabs table has 3 full-width rules: top, mid (below header), bottom
            if full_rules_crossed >= 3 and len(picked_rows) >= 3:
                break
            if _is_prose_row(row_text, row_w, col_w, has_multi_spans):
                break
        elif not picked_rows and full_new:
            full_rules_crossed += len(full_new)

        if _is_prose_row(row_text, row_w, col_w, has_multi_spans):
            break
        if (not picked_rows and gap > 3.5 * lh) or (len(picked_rows) >= 2 and gap > 2.6 * lh):
            break
        if len(picked_rows) >= 2 and gap >= 0.8 * lh and HEADING_RE.match(row_text):
            break

        picked_rows.append(r)
        edge = max(edge, r["y1"]) if direction == "below" else min(edge, r["y0"])

    picked = [l for r in picked_rows for l in r["lines"]]
    return picked if len(picked_rows) >= 2 else []


def extract_tables_with_anchors(page, plpage, lines, words, captions, registry,
                                tables_dir, rel_base, page_no, gutter, scanned, h_rules=None):
    """Locate tables via their captions, extract them, write CSVs, fill the registry."""
    pw = page.rect.width
    use_plumber = plpage is not None and not scanned and page.rotation == 0
    shift = (plpage.bbox[0], plpage.bbox[1]) if plpage is not None else (0.0, 0.0)
    caption_ids = set(id(l) for c in captions for l in c["lines"])
    if h_rules is None:
        h_rules = [] if scanned else _get_horizontal_rules(page)
    os.makedirs(tables_dir, exist_ok=True)
    count = 0
    for cap in sorted((c for c in captions if c["kind"] == "table"),
                      key=lambda c: (round(c["bbox"][1] / 10.0), c["bbox"][0])):
        region = _table_region_from_rules(cap, pw, gutter, h_rules)
        df = tb = None
        for direction in ("below", "above"):          # captions usually sit above
            picked = _scan_table_lines(cap, lines, region, direction, captions,
                                       caption_ids, h_rules=h_rules)
            if not picked:
                continue
            ub = _union([l.bbox for l in picked])
            top, bot = ub[1] - 6.0, ub[3] + 6.0
            if direction == "below":
                top = max(top, cap["bbox"][3] + 0.5)
            else:
                bot = min(bot, cap["bbox"][1] - 0.5)
            search = (max(region[0], ub[0] - 6.0) if gutter else ub[0] - 6.0, top,
                      min(region[1], ub[2] + 6.0) if gutter else ub[2] + 6.0, bot)
            wide = (max(region[0], search[0] - 30.0), search[1],
                    min(region[1], search[2] + 30.0), search[3])
            try:
                df, tb = _extract_table_in_bbox(page, plpage, shift, words, search,
                                                use_plumber, wide, h_rules=h_rules)
            except Exception as exc:
                log.warning("p%d: table extraction error: %s", page_no, exc)
                df = tb = None
            if df is not None:
                break
        if df is None:
            log.info("p%d: '%s' rejected (no valid table found)", page_no, cap["label"])
            continue
        if any(_inter_area(tb, r["table_bbox"]) > 0.5 * _area(tb)
               for r in registry if r["kind"] == "table"):
            continue
        count += 1
        path = os.path.join(tables_dir, "page_%d_table_%d.csv" % (page_no, count))
        rel = os.path.relpath(path, rel_base).replace(os.sep, "/")
        df.to_csv(path, index=False, header=False, encoding="utf-8")
        # Include the caption AND the aligned table content together in the text output
        table_txt = _format_df_as_text_table(df)
        placeholder_block = '%s\n[TABLE: %s]\n%s' % (cap["text"], rel, table_txt)
        registry.append({
            "kind": "table", "table_bbox": tb,
            "mask_bbox": _union([cap["bbox"], tb]),
            "placeholder": placeholder_block})
        log.info("p%d: saved %s (%d x %d)", page_no, rel, df.shape[0], df.shape[1])
    return count



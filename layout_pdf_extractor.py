@dataclass
class TextLine:
    x0: float
    y0: float
    x1: float
    y1: float
    text: str
    size: float = 10.0
    bold: bool = False
    kind: str = "text"            # "text" | "placeholder"

    @property
    def bbox(self):
        return (self.x0, self.y0, self.x1, self.y1)

    @property
    def width(self):
        return self.x1 - self.x0

    @property
    def height(self):
        return max(self.y1 - self.y0, 0.1)

    @property
    def cx(self):
        return (self.x0 + self.x1) / 2.0

    @property
    def cy(self):
        return (self.y0 + self.y1) / 2.0


def _union(boxes):
    boxes = [b for b in boxes if b is not None]
    return (min(b[0] for b in boxes), min(b[1] for b in boxes),
            max(b[2] for b in boxes), max(b[3] for b in boxes))


def _area(b):
    return max(b[2] - b[0], 0.0) * max(b[3] - b[1], 0.0)


def _inter_area(a, b):
    return _area((max(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), min(a[3], b[3])))


def _expand(b, m):
    return (b[0] - m, b[1] - m, b[2] + m, b[3] + m)


def _overlaps(a, b):
    return not (a[2] < b[0] or b[2] < a[0] or a[3] < b[1] or b[3] < a[1])


def _center(b):
    return ((b[0] + b[2]) / 2.0, (b[1] + b[3]) / 2.0)


def _center_inside(b, container):
    cx, cy = _center(b)
    return container[0] <= cx <= container[2] and container[1] <= cy <= container[3]


def _x_overlap_ratio(b, x0, x1):
    w = max(b[2] - b[0], 0.01)
    return max(0.0, min(b[2], x1) - max(b[0], x0)) / w


def _median(values, default=10.0):
    values = sorted(values)
    if not values:
        return default
    return values[len(values) // 2]


def _paragraph_like(line):
    t = line.text
    if len(t) < 55:
        return False
    return sum(c.isalpha() for c in t) / float(len(t)) >= 0.6



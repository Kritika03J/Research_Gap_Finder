def detect_gutter(lines, page_w):
    """
    x of the vertical whitespace gutter of a 2-column page, else None.
    Ignores explicitly full-width spanning lines (e.g. wide table captions) so
    hybrid pages with both full-width tables (Tables I & II) and 2-column text/tables
    (Tables III & IV) still detect their 2-column gutter properly.
    """
    if len(lines) < 6:
        return None
    col_candidates = [l for l in lines if l.width <= FULL_WIDTH_RATIO * page_w]
    if len(col_candidates) < 6:
        return None
    best_cross, hits = None, []
    for x in range(int(0.38 * page_w), int(0.62 * page_w) + 1, 2):
        cross = left = right = 0
        for l in col_candidates:
            if l.x0 < x - 2 and l.x1 > x + 2:
                cross += 1
            elif l.x1 <= x + 2:
                left += 1
            elif l.x0 >= x - 2:
                right += 1
        if left < 3 or right < 3:
            continue
        if cross > max(2, 0.22 * (cross + left + right)):
            continue
        if best_cross is None or cross < best_cross:
            best_cross, hits = cross, [x]
        elif cross == best_cross:
            hits.append(x)
    if not hits:
        return None
    return sum(hits) / float(len(hits))


def _column_region(bbox, page_w, gutter):
    """x-range (left, right) of the column / full width an object belongs to."""
    if gutter is None:
        return (0.0, page_w)
    w = bbox[2] - bbox[0]
    if (bbox[0] < gutter - 3 and bbox[2] > gutter + 3) or w > FULL_WIDTH_RATIO * page_w:
        return (0.0, page_w)
    if (bbox[0] + bbox[2]) / 2.0 < gutter:
        return (0.0, gutter + 2.0)
    return (gutter - 2.0, page_w)



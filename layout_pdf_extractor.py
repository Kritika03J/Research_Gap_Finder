def _collect_graphics(page, table_boxes):
    """Vector drawings + embedded bitmaps as bbox tuples (tables excluded)."""
    pr = page.rect
    items = []
    try:
        for d in page.get_drawings():
            r = d["rect"]
            b = (r.x0, r.y0, r.x1, r.y1)
            w, h = b[2] - b[0], b[3] - b[1]
            if w < 0.01 and h < 0.01:
                continue
            if _area(b) > 0.8 * pr.get_area():
                continue
            if h <= 1.5 and w > 0.8 * pr.width:        # header / footer rules
                continue
            items.append(b)
    except Exception as exc:
        log.debug("get_drawings failed: %s", exc)
    try:
        for info in page.get_image_info():
            r = fitz.Rect(info["bbox"])
            if r.width < 4 or r.height < 4 or r.get_area() > 0.9 * pr.get_area():
                continue
            items.append((r.x0, r.y0, r.x1, r.y1))
    except Exception as exc:
        log.debug("get_image_info failed: %s", exc)
    return [g for g in items
            if not any(_center_inside(g, _expand(t, 3.0)) for t in table_boxes)]


def _locate_figure_bbox(graphics, lines, cap, region, direction, other_caps, caption_ids):
    cb = cap["bbox"]
    xr0, xr1 = region
    body_size = _median([l.size for l in lines if _paragraph_like(l)]
                        or [l.size for l in lines], 10.0)

    def blocked(g):
        for c in other_caps:
            if c is cap or _x_overlap_ratio(c["bbox"], xr0, xr1) < 0.3:
                continue
            if direction == "above" and c["bbox"][1] >= g[3] - 1 and c["bbox"][3] <= cb[1] + 1:
                return True
            if direction == "below" and c["bbox"][3] <= g[1] + 1 and c["bbox"][1] >= cb[3] - 1:
                return True
        return False

    if direction == "above":
        cand = [g for g in graphics if g[3] <= cb[1] + 2]
        dist = lambda g: cb[1] - g[3]
    else:
        cand = [g for g in graphics if g[1] >= cb[3] - 2]
        dist = lambda g: g[1] - cb[3]

    cand = [g for g in cand if xr0 - 1 <= (g[0] + g[2]) / 2.0 <= xr1 + 1 and not blocked(g)]
    if not cand:
        return None
    seed = min(cand, key=dist)
    if dist(seed) > FIG_MAX_GAP:
        return None

    if direction == "above":
        pool = [l for l in lines if l.y1 <= cb[1] + 1]
    else:
        pool = [l for l in lines if l.y0 >= cb[3] - 1]
    pool = [l for l in pool if id(l) not in caption_ids
            and _x_overlap_ratio(l.bbox, xr0, xr1) >= 0.5
            and not _paragraph_like(l)
            and not (l.bold and HEADING_RE.match(l.text))]

    box = seed
    used_g, used_l = {seed}, set()
    side_by_side_done = False
    while True:
        changed = False
        ex = _expand(box, FIG_GRAPHIC_TOL)
        for g in cand:
            if g not in used_g and _overlaps(ex, g):
                used_g.add(g)
                box = _union([box, g])
                changed = True
        ex_t = _expand(box, FIG_TEXT_TOL)
        for l in pool:
            if id(l) in used_l:
                continue
            inside = _inter_area(l.bbox, box) > 0.5 * _area(l.bbox)
            near = _overlaps(ex_t, l.bbox) and len(l.text) <= 60
            if not (inside or near):
                continue
            if not inside:
                far = (l.y1 <= box[1] + 1) if direction == "above" else (l.y0 >= box[3] - 1)
                if far and not (l.size <= 0.92 * body_size and len(l.text) <= 40):
                    continue
            used_l.add(id(l))
            box = _union([box, l.bbox])
            changed = True
        if not changed and not side_by_side_done:
            side_by_side_done = True
            for g in cand:
                cy = (g[1] + g[3]) / 2.0
                if g not in used_g and box[1] <= cy <= box[3]:
                    used_g.add(g)
                    box = _union([box, g])
                    changed = True
        if not changed:
            break
    return box


def _scanned_figure_bbox(lines, cap, region, page_h, page_img, dpi):
    """Scanned pages: figure = blank/short-text band above the caption with ink in it."""
    cb = cap["bbox"]
    xr0, xr1 = region
    above = sorted([l for l in lines if l.y1 <= cb[1] + 1 and xr0 - 2 <= l.cx <= xr1 + 2
                    and id(l) not in set(id(c) for c in cap["lines"])],
                   key=lambda l: -l.y1)
    top = 0.04 * page_h
    for l in above:
        if _paragraph_like(l):
            top = l.y1 + 2.0
            break
    box = (xr0, top, xr1, cb[1] - 1.0)
    if box[3] - box[1] < 60:
        return None
    if page_img is not None:
        s = dpi / 72.0
        crop = page_img.crop(tuple(int(v * s) for v in box)).convert("L")
        hist = crop.histogram()
        if sum(hist[:200]) / float(max(crop.size[0] * crop.size[1], 1)) < 0.01:
            return None
    return box


def _render_clip(page, bbox, path, dpi=FIGURE_DPI):
    clip = fitz.Rect(bbox) & page.rect
    if clip.is_empty:
        raise ValueError("empty clip")
    pix = page.get_pixmap(matrix=fitz.Matrix(dpi / 72.0, dpi / 72.0), clip=clip, alpha=False)
    pix.save(path)


def _clamp_figure_to_text(fig, box, lines, skip_ids):
    """Shrink the padded figure rect so it never covers text that is not part of `box`."""
    x0, y0, x1, y1 = fig
    for l in lines:
        if id(l) in skip_ids or _center_inside(l.bbox, box):
            continue
        if _inter_area(l.bbox, (x0, y0, x1, y1)) <= 0:
            continue
        if l.cy <= box[1]:
            y0 = max(y0, l.y1 + 0.5)
        elif l.cy >= box[3]:
            y1 = min(y1, l.y0 - 0.5)
        elif l.cx <= box[0]:
            x0 = max(x0, l.x1 + 0.5)
        else:
            x1 = min(x1, l.x0 - 0.5)
    return (x0, y0, x1, y1)


def extract_figures_with_anchors(page, lines, captions, registry, figures_dir, rel_base,
                                 page_no, gutter, scanned, page_img=None, dpi=FIGURE_DPI):
    """Locate figures via captions, aggregate vector paths + labels, render to PNG."""
    pw, ph = page.rect.width, page.rect.height
    os.makedirs(figures_dir, exist_ok=True)
    table_boxes = [r["table_bbox"] for r in registry if r["kind"] == "table"]
    graphics = [] if scanned else _collect_graphics(page, table_boxes)
    caption_ids = set(id(l) for c in captions for l in c["lines"])
    count = 0
    for cap in sorted((c for c in captions if c["kind"] == "figure"),
                      key=lambda c: c["bbox"][1]):
        region = _column_region(cap["bbox"], pw, gutter)
        claimed = [r["mask_bbox"] for r in registry if r["kind"] == "figure"]
        free = [g for g in graphics if not any(_center_inside(g, c) for c in claimed)]
        box = None
        if scanned:
            box = _scanned_figure_bbox(lines, cap, region, ph, page_img, OCR_DPI)
        else:
            for direction in ("above", "below"):
                box = _locate_figure_bbox(free, lines, cap, region, direction,
                                          captions, caption_ids)
                if box is not None:
                    break
        if box is None or (box[2] - box[0]) < 30 or (box[3] - box[1]) < 30:
            log.info("p%d: '%s' has no graphic nearby, left in text", page_no, cap["label"])
            continue
        cb = cap["bbox"]
        fig = (box[0] - FIG_MARGIN, box[1] - FIG_MARGIN, box[2] + FIG_MARGIN, box[3] + FIG_MARGIN)
        if box[3] <= cb[1] + 2:
            fig = (fig[0], fig[1], fig[2], min(fig[3], cb[1] - 0.5))
        else:
            fig = (fig[0], max(fig[1], cb[3] + 0.5), fig[2], fig[3])
        fig = _clamp_figure_to_text(fig, box, lines, caption_ids)
        fig = (max(fig[0], 0), max(fig[1], 0), min(fig[2], pw), min(fig[3], ph))
        count += 1
        path = os.path.join(figures_dir, "page_%d_figure_%d.png" % (page_no, count))
        rel = os.path.relpath(path, rel_base).replace(os.sep, "/")
        try:
            _render_clip(page, fig, path, dpi)
        except Exception as exc:
            log.warning("p%d: could not render %s: %s", page_no, rel, exc)
            count -= 1
            continue
        registry.append({
            "kind": "figure", "table_bbox": None,
            "mask_bbox": _union([fig, cb]),
            "placeholder": '[FIGURE: %s - Caption: "%s"]' % (rel, cap["text"])})
        log.info("p%d: saved %s", page_no, rel)
    return count



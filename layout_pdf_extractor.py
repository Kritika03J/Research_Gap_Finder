# Page-1 header (title + multi-column author block)
# --------------------------------------------------------------------------- #
def extract_header_block(lines, page_w, page_h):
    """
    Returns (header_lines, header_text, header_bbox) for page 1.
    Extracts title and decomposes author blocks into distinct author cards
    across any number of author columns (1, 2, 3, or 4 columns).
    """
    if len(lines) < 3:
        return [], "", None
    ordered = sorted(lines, key=lambda l: (l.y0, l.x0))
    sizes = [l.size for l in ordered]
    body_size = _median([l.size for l in ordered if _paragraph_like(l)] or sizes)

    # --- title = the biggest-font lines in the upper part of the page
    mx = max(sizes)
    title, title_top, title_bot = [], None, None
    if mx >= 1.25 * body_size:
        title = [l for l in ordered if l.size >= 0.82 * mx and l.y0 < 0.35 * page_h]
    if title:
        title_top = min(l.y0 for l in title)
        title_bot = max(l.y1 for l in title)
    title_ids = set(id(l) for l in title)

    # --- header end: first body-column line (any column) or Abstract / Index Terms
    def body_like(l):
        return (id(l) not in title_ids and len(l.text) >= 40 and l.width >= 0.28 * page_w
                and l.size <= 1.15 * body_size)

    cands = [l for l in ordered if body_like(l) and (title_bot is None or l.y0 > title_bot)]
    ends = []
    for l in cands:
        if sum(1 for m in cands if abs(m.x0 - l.x0) <= 8) >= 4:
            ends.append(l.y0)
            break
    for idx, l in enumerate(ordered):
        if idx >= 2 and l.y0 > 0.08 * page_h and ABSTRACT_RE.match(l.text):
            ends.append(l.y0)
            break
    if not ends:
        for idx, l in enumerate(ordered):
            if idx >= 3 and _paragraph_like(l) and l.width > 0.35 * page_w:
                ends.append(l.y0)
                break
    if not ends:
        return [], "", None
    end_y = min(ends)
    header = [l for l in ordered if l.y0 < end_y - 1]
    if not header or max(l.y1 for l in header) > 0.7 * page_h:
        return [], "", None

    if not title:
        title = [header[0]]
        title_ids = set(id(l) for l in title)
        title_top = title[0].y0
    title = [l for l in title if l in header] or [header[0]]
    pre = [l for l in header if id(l) not in title_ids and l.y1 <= title_top + 1]
    pre_ids = set(id(l) for l in pre)
    rest = [l for l in header if id(l) not in title_ids and id(l) not in pre_ids]

    parts = []
    # Title
    parts.append(" ".join(l.text for l in sorted(title, key=lambda l: (round(l.cy / 2.0), l.x0))))

    # --- Author Block Parsing (supports 1, 2, 3, or N author columns)
    if rest:
        med_h = _median([l.height for l in rest], 10.0)

        # Separate any full-width lines (e.g. shared affiliation banner) from column lines
        wide_lines = [l for l in rest if l.width > 0.65 * page_w]
        col_lines = [l for l in rest if l.width <= 0.65 * page_w]

        # 1. Cluster author lines into N horizontal columns by their X-centre (cx)
        # In multi-column author grids (2-col, 3-col, 4-col), lines belonging to the
        # same author column have closely aligned centres (or overlapping x-spans).
        col_clusters = []
        for l in sorted(col_lines, key=lambda x: x.cx):
            placed = False
            for cl in col_clusters:
                cl_cx = sum(item.cx for item in cl) / float(len(cl))
                cl_x0 = min(item.x0 for item in cl)
                cl_x1 = max(item.x1 for item in cl)
                ov = min(l.x1, cl_x1) - max(l.x0, cl_x0)
                if abs(l.cx - cl_cx) <= 0.12 * page_w or ov > 0.35 * min(l.width, cl_x1 - cl_x0):
                    cl.append(l)
                    placed = True
                    break
            if not placed:
                col_clusters.append([l])

        # Sort column clusters left-to-right
        col_clusters.sort(key=lambda cl: sum(item.cx for item in cl) / float(len(cl)))

        # 2. Within each author column, group lines vertically into individual author cards
        for side_lines in col_clusters:
            sorted_side = sorted(side_lines, key=lambda l: (l.y0, l.x0))
            authors_in_col = []
            cur_author = [sorted_side[0]]

            for prev_l, cur_l in zip(sorted_side[:-1], sorted_side[1:]):
                v_gap = cur_l.y0 - prev_l.y1
                prev_txt = prev_l.text.strip()
                cur_txt = cur_l.text.strip()

                # Check if previous line was a wrapped email tail (e.g. "ae") or complete email
                prev_is_complete_email = (
                    "@" in prev_txt and not prev_txt.endswith(".")
                )
                prev_is_wrapped_email_tail = (
                    len(cur_author) >= 2
                    and "@" in cur_author[-2].text
                    and cur_author[-2].text.strip().endswith(".")
                    and len(prev_txt) <= 6
                )
                # Don't split if current line is just the wrapped 2nd line of an email (e.g. "ae")
                cur_is_email_continuation = (
                    "@" in prev_txt and prev_txt.endswith(".") and len(cur_txt) <= 6
                )

                if not cur_is_email_continuation and (
                    v_gap > 1.25 * med_h
                    or prev_is_complete_email
                    or prev_is_wrapped_email_tail
                ):
                    authors_in_col.append(cur_author)
                    cur_author = [cur_l]
                else:
                    cur_author.append(cur_l)
            if cur_author:
                authors_in_col.append(cur_author)

            # Output each author's lines in clean top-to-bottom order
            for author_lines in authors_in_col:
                author_lines.sort(key=lambda l: (round(l.cy / 2.0), l.x0))
                card_text = "\n".join(l.text.strip() for l in author_lines if l.text.strip())
                if card_text:
                    parts.append(card_text)

        for wl in sorted(wide_lines, key=lambda l: l.y0):
            if wl.text.strip():
                parts.append(wl.text.strip())

    text = "\n\n".join(p for p in parts if p.strip())
    return header, text, _union([l.bbox for l in header])



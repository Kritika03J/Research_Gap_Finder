# Per-page pipeline + main
# --------------------------------------------------------------------------- #
def process_page(page, plpage, page_index, tables_dir, figures_dir, rel_base,
                 min_chars=MIN_CHARS_PER_PAGE, ocr_dpi=OCR_DPI, figure_dpi=FIGURE_DPI,
                 debug_dir=None):
    page_no = page_index + 1
    pw, ph = page.rect.width, page.rect.height
    scanned = detect_scanned_page(page, min_chars)
    page_img = None
    if scanned:
        try:
            lines, words, page_img = _ocr_lines_and_words(page, ocr_dpi)
        except Exception as exc:       # tesseract missing / failed -> try digital text
            log.warning("p%d: OCR failed (%s); falling back to embedded text", page_no, exc)
            scanned = False
            lines, words = _digital_lines_and_words(page)
    else:
        lines, words = _digital_lines_and_words(page)
    if not lines:
        log.info("p%d: no text found", page_no)
        return ""
    lines = drop_page_furniture(
        split_side_by_side_captions(merge_row_fragments(lines), words), ph)

    header_text, _hb = "", None
    if page_index == 0:
        header_lines, header_text, _hb = extract_header_block(lines, pw, ph)
        hid = set(id(l) for l in header_lines)
        lines = [l for l in lines if id(l) not in hid]

    h_rules = [] if scanned else _get_horizontal_rules(page)
    gutter = detect_gutter(lines, pw)
    captions = detect_captions(lines, h_rules=h_rules)
    registry = []
    try:
        extract_tables_with_anchors(page, plpage, lines, words, captions, registry,
                                    tables_dir, rel_base, page_no, gutter, scanned,
                                    h_rules=h_rules)
    except Exception as exc:
        log.warning("p%d: table stage failed: %s", page_no, exc)
    try:
        extract_figures_with_anchors(page, lines, captions, registry, figures_dir, rel_base,
                                     page_no, gutter, scanned, page_img, figure_dpi)
    except Exception as exc:
        log.warning("p%d: figure stage failed: %s", page_no, exc)

    if debug_dir:
        try:
            os.makedirs(debug_dir, exist_ok=True)
            save_debug_image(page, os.path.join(debug_dir, "page_%d_debug.png" % page_no),
                             _hb, captions, registry, gutter)
        except Exception as exc:
            log.warning("p%d: debug image failed: %s", page_no, exc)
    body = mask_and_compile_text(lines, registry, pw, ph, gutter)
    return "\n\n".join(p for p in (header_text, body) if p)


def main(pdf_path=None, output_dir=None, argv=None):
    ap = argparse.ArgumentParser(description="Extract text, tables and figures from a paper.")
    ap.add_argument("pdf_path")
    ap.add_argument("output_dir", nargs="?", default=None,
                    help="base folder (optional if -o / --tables-dir / --figures-dir are given)")
    ap.add_argument("-o", "--output", help="text file path (default: <output_dir>/extracted_text.txt)")
    ap.add_argument("--tables-dir", help="folder for table CSVs (default: <output_dir>/tables)")
    ap.add_argument("--figures-dir", help="folder for figure PNGs (default: <output_dir>/images)")
    ap.add_argument("--debug", metavar="DIR", help="save annotated page images here")
    ap.add_argument("--dpi", type=int, default=FIGURE_DPI, help="figure render DPI")
    ap.add_argument("--min-chars", type=int, default=MIN_CHARS_PER_PAGE)
    ap.add_argument("--page-markers", action="store_true")
    ap.add_argument("-v", "--verbose", action="store_true")
    if argv is None and pdf_path is not None:
        argv = [pdf_path] + ([output_dir] if output_dir else [])
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    log.setLevel(logging.DEBUG if args.verbose else logging.INFO)
    for noisy in ("pdfminer", "pdfplumber", "PIL"):
        logging.getLogger(noisy).setLevel(logging.WARNING)

    if not os.path.isfile(args.pdf_path):
        log.error("PDF not found: %s", args.pdf_path)
        return 1
    base = args.output_dir or "."
    out_txt = args.output or os.path.join(base, "extracted_text.txt")
    tables_dir = args.tables_dir or os.path.join(base, "tables")
    figures_dir = args.figures_dir or os.path.join(base, "images")
    rel_base = os.path.dirname(os.path.abspath(out_txt))
    for d in (rel_base, tables_dir, figures_dir):
        os.makedirs(d, exist_ok=True)
    if pytesseract is not None:
        try:
            pytesseract.get_tesseract_version()
        except Exception:
            log.warning("tesseract binary not found - scanned pages will not be OCR'd")

    try:
        doc = fitz.open(args.pdf_path)
    except Exception as exc:
        log.error("cannot open PDF: %s", exc)
        return 1
    try:
        plpdf = pdfplumber.open(args.pdf_path)
    except Exception as exc:
        log.warning("pdfplumber could not open the PDF (%s); table fallback only", exc)
        plpdf = None

    chunks = []
    for i in range(doc.page_count):
        try:
            plpage = plpdf.pages[i] if plpdf is not None else None
            text = process_page(doc[i], plpage, i, tables_dir, figures_dir, rel_base,
                                args.min_chars, OCR_DPI, args.dpi, args.debug)
        except Exception as exc:
            log.error("page %d failed: %s", i + 1, exc, exc_info=args.verbose)
            text = ""
        if args.page_markers:
            text = "=== Page %d ===\n\n%s" % (i + 1, text)
        if text.strip():
            chunks.append(text)
        if plpage is not None:
            try:
                plpage.close()
            except Exception:
                pass

    with open(out_txt, "w", encoding="utf_8") as fh:
        fh.write("\n\n".join(chunks) + "\n")
    log.info("done -> %s", out_txt)
    doc.close()
    if plpdf is not None:
        plpdf.close()
    return 0



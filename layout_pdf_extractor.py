def _is_caption_start(text, regex):
    m = regex.match(text)
    if not m:
        return False
    tail = text[m.end():].lstrip()
    if m.group(0).rstrip().endswith((":", ".")) and not m.group(0).rstrip().endswith("Fig."):
        return True
    return tail == "" or tail[0].isupper() or tail[0] in "-\u2013\u2014|("


def detect_captions(lines, h_rules=None):
    """
    Find 'Table N' / 'Figure N' captions and merge their continuation lines
    (including short wrapped words like 'MODEL' above the top table border rule).
    """
    caps, used = [], set()
    ordered = sorted(lines, key=lambda l: (l.y0, l.x0))
    for i, ln in enumerate(ordered):
        if id(ln) in used:
            continue
        if _is_caption_start(ln.text, TABLE_CAPTION_RE):
            kind = "table"
        elif _is_caption_start(ln.text, FIGURE_CAPTION_RE):
            kind = "figure"
        else:
            continue
        group = [ln]
        used.add(id(ln))
        last = ln

        # Find the first horizontal rule below the caption start in its x-range
        first_rule_y = None
        if kind == "table" and h_rules:
            cands = [
                ry for rx0, ry, rx1 in h_rules
                if ry >= ln.y1 - 1.0
                and min(ln.x1, rx1) - max(ln.x0, rx0) > 0.25 * min(ln.width, rx1 - rx0)
            ]
            if cands:
                first_rule_y = min(cands)

        for nxt in ordered[i + 1:]:
            if id(nxt) in used or len(group) >= 8:
                continue
            # Must horizontally overlap with the first caption line (same column)
            horiz_ov = min(ln.x1, nxt.x1) - max(ln.x0, nxt.x0)
            if horiz_ov <= 0:
                continue
            # Never cross the top horizontal border rule of the table
            if first_rule_y is not None and nxt.cy >= first_rule_y:
                break
            gap = nxt.y0 - last.y1
            if gap > 0.85 * last.height:
                if nxt.y0 > last.y1 + 2.5 * last.height:
                    break
                continue
            if (abs(nxt.size - ln.size) <= 0.20 * ln.size
                    and not TABLE_CAPTION_RE.match(nxt.text)
                    and not FIGURE_CAPTION_RE.match(nxt.text)
                    and not _paragraph_like(nxt)):
                group.append(nxt)
                used.add(id(nxt))
                last = nxt
        text = re.sub(r"\s+", " ", " ".join(g.text for g in group)).strip()
        label = re.match(r"^\s*([A-Za-z.]+\s*[0-9IVXLC]+)", text)
        caps.append({"kind": kind, "lines": group,
                     "bbox": _union([g.bbox for g in group]),
                     "text": text.replace('"', "'"),
                     "label": label.group(1) if label else ""})
    return caps


